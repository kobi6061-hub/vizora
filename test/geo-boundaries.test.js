'use strict';
/* PROPX · map geography (lib/geo/boundaries.js) — the gates: real boundaries from Natural Earth, geometry only, every district
 * present, rings inside Israel's extent, the page and the offline build load it, the hand-drawn fallback kept, the projection true. */
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const ROOT = path.join(__dirname, '..');
let passed = 0, failed = 0;
const t = (name, fn) => { try { fn(); passed++; console.log('  ✓ ' + name); } catch (e) { failed++; console.log('  ✗ ' + name + '\n    ' + String(e && e.stack || e).split('\n').slice(0, 4).join('\n    ')); } };
const SRC = fs.readFileSync(path.join(ROOT, 'lib/geo/boundaries.js'), 'utf8');
require(path.join(ROOT, 'lib/geo/boundaries.js'));
const G = globalThis.PROPX_GEO;
const INDEX = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const STANDALONE = fs.readdirSync(path.join(ROOT, 'standalone')).filter((f) => f.endsWith('.html')).map((f) => fs.readFileSync(path.join(ROOT, 'standalone', f), 'utf8'));

console.log('geo boundaries: the module');
t('generated from Natural Earth (public domain), geometry only: a version, the source, the licence, a bilingual basis; no market field, no number that is not a coordinate', () => {
  assert.equal(G.version, 1); assert.match(G.source, /Natural Earth/); assert.match(G.licence, /public domain/); assert.ok(G.basis.he && G.basis.en);
  assert.match(SRC, /generated by scripts\/build-geo-boundaries\.py/); assert.ok(!/price|sales|units|tx|yield|rent/i.test(JSON.stringify(Object.keys(G))));
  assert.ok(fs.existsSync(path.join(ROOT, 'scripts/build-geo-boundaries.py')));
});
t('the six CBS districts by their PROPX ids, the country outline, the West Bank and Gaza — every ring ≥ 20 vertices of [lat, lng] inside Israel\'s extent (29.4–33.5 N, 34.1–35.95 E), 4 decimals, no duplicate closing point', () => {
  assert.deepEqual(Object.keys(G.districts).sort(), ['d-center', 'd-haifa', 'd-jm', 'd-north', 'd-south', 'd-ta']);
  assert.deepEqual(Object.keys(G.areas).sort(), ['gaza', 'westBank']);
  const rings = [...Object.values(G.districts), G.land, ...Object.values(G.areas)];
  for (const r of rings) { assert.ok(r.length >= 20); assert.notDeepEqual(r[0], r[r.length - 1]);
    for (const [lat, lng] of r) { assert.ok(lat >= 29.4 && lat <= 33.5 && lng >= 34.1 && lng <= 35.95, `${lat},${lng}`); assert.ok(String(lat).split('.')[1] == null || String(lat).split('.')[1].length <= 4); } }
  assert.deepEqual(G.counts['d-ta'], G.districts['d-ta'].length); assert.ok(G.land.length >= 300);
  /* the Jerusalem district spans the whole city (CBS), Tel Aviv is the smallest, the South the widest */
  const span = (r) => Math.max(...r.map((p) => p[1])) - Math.min(...r.map((p) => p[1]));
  assert.ok(span(G.districts['d-jm']) > 0.4); assert.ok(G.districts['d-ta'].length < G.districts['d-south'].length);
});
t('deterministic and compact: the same rings serialise to the same bytes twice; the module is under 60 KB and never closes a script element (it is inlined)', () => {
  assert.equal(JSON.stringify(G.districts), JSON.stringify(require(path.join(ROOT, 'lib/geo/boundaries.js')) && globalThis.PROPX_GEO.districts));
  assert.ok(SRC.length < 60000); assert.ok(!/<\/script/i.test(SRC));
});

console.log('geo boundaries: the page');
t('the page loads the module after the registry and draws the districts from it (ringPath / GEO) with the hand-drawn constants kept as the fallback; the projection keeps the true aspect at 31.45° N', () => {
  assert.match(INDEX, /<script src="\/lib\/explain\/registry\.js"><\/script>\n<script src="\/lib\/geo\/boundaries\.js"><\/script>/);
  assert.match(INDEX, /const GEO=\(typeof window!=="undefined"&&window\.PROPX_GEO&&window\.PROPX_GEO\.districts&&window\.PROPX_GEO\.land\)\?window\.PROPX_GEO:null;/);
  assert.match(INDEX, /const israelPath=GEO\?ringPath\(GEO\.land\)\+ringPath\(GEO\.areas\.westBank\)\+ringPath\(GEO\.areas\.gaza\)/);
  assert.match(INDEX, /GEO&&GEO\.districts\[id\]\?ringPath\(GEO\.districts\[id\]\):DISTRICT_POLY\[id\]/);
  assert.match(INDEX, /const ISRAEL_PTS=\[/); assert.match(INDEX, /const DISTRICT_POLY=\{/);
  assert.match(INDEX, /MAP_KX=MAP_KY\*Math\.cos\(31\.45\*Math\.PI\/180\)/); assert.match(INDEX, /const proj=\(lat,lng\)=>\[ \(lng-MAP_LNG0\)\*MAP_KX, \(MAP_LAT_TOP-lat\)\*MAP_KY \];/);
});
t('the West Bank and Gaza are hatched areas with a label, never clickable and never a data node; the sea and the coastline are drawn; the ranking gate of renderMap is untouched', () => {
  assert.match(INDEX, /class="map-area" d="\$\{areaPath\(k\)\}"/); assert.match(INDEX, /\.map-area\{fill:url\(#mapHatch\);stroke:var\(--baseline\);pointer-events:none\}/);
  assert.ok(!/class="map-area"[^>]*data-loc/.test(INDEX)); assert.match(INDEX, /class="map-sea"/); assert.match(INDEX, /class="map-coast"/);
  assert.match(INDEX, /if\(rankable\(mm\.f,ctx\.items\)\)\{/);
});
t('the offline build inlines the module (no network, no credential) and the build script refuses a module that closes the script element', () => {
  for (const s of STANDALONE) { assert.ok(!/<script src="\/lib\/geo\/boundaries\.js">/.test(s)); assert.ok(s.includes('root.PROPX_GEO = ')); }
  const build = fs.readFileSync(path.join(ROOT, 'scripts/build-standalone.py'), 'utf8'); assert.match(build, /TAG5 = '<script src="\/lib\/geo\/boundaries\.js"><\/script>'/); assert.match(build, /geo boundaries must not close the script element/);
});
console.log(`geo boundaries: ${passed} passed${failed ? `, ${failed} FAILED` : ''}`);
process.exit(failed ? 1 : 0);
